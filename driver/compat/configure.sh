#!/bin/sh
# Detect the target DRM interfaces with Kbuild, including stable backports.
set -eu

kdir=${1:?kernel build directory is required}
output=${2:?output header is required}
make_cmd=${3:-make}
script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
work=$(mktemp -d "${TMPDIR:-/tmp}/matebook-drm-compat.XXXXXX")
header="$output.tmp.$$"
trap 'rm -rf -- "$work"; rm -f -- "$header"' EXIT HUP INT TERM
cp "$script_dir/Makefile" "$work/Makefile"

probe() {
    cp "$script_dir/$1.c" "$work/conftest.c"
    rm -f "$work/conftest.o" "$work/.conftest.o.cmd"
    "$make_cmd" -s --no-print-directory -C "$kdir" M="$work" \
        MATEBOOK_TEST_FORCE="$2" conftest.o >"$work/$1-$2.log" 2>&1
}

detect() {
    if probe "$1" 1; then
        printf '#define %s 1\n' "$2"
    elif probe "$1" 0; then
        printf '#define %s 0\n' "$2"
    else
        printf 'Cannot identify the target DRM %s API:\n' "$1" >&2
        cat "$work/$1-1.log" "$work/$1-0.log" >&2
        exit 1
    fi
}

{
    printf '/* Generated by compat/configure.sh for the target kernel. */\n'
    printf '#ifndef MATEBOOK_KERNEL_COMPAT_H\n#define MATEBOOK_KERNEL_COMPAT_H\n'
    detect fb-helper-restore MATEBOOK_DRM_FB_HELPER_RESTORE_HAS_FORCE
    detect client-restore MATEBOOK_DRM_CLIENT_RESTORE_HAS_FORCE
    printf '#endif\n'
} >"$header"

if ! cmp -s "$header" "$output"; then
    mv "$header" "$output"
fi
